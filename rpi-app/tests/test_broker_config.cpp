// Parsing of the broker config file; pure function, needs no broker or privileges.
#include "../broker_config.hpp"

#include <cassert>
#include <sstream>

namespace
{
bool parse(const std::string& text, BrokerConfig& config, std::string& error)
{
    std::istringstream in(text);
    return parse_broker_config(in, config, error);
}

void check_full_config()
{
    BrokerConfig config;
    std::string error;
    const std::string text = "# generated by emulator/stand/lib.sh\n"
                             "\n"
                             "host = 10.0.2.2\n"
                             "port=8883\n"
                             "user=edge\n"
                             "password=pw=with=equals\n"
                             "cafile=/etc/edge/ca.crt\n"
                             "topic_root=mesh-a/7F10/21A0\n"
                             "client_id=edge-1\n";
    assert(parse(text, config, error));
    assert(config.host == "10.0.2.2");
    assert(config.port == 8883);
    assert(config.user == "edge");
    assert(config.password == "pw=with=equals");
    assert(config.cafile == "/etc/edge/ca.crt");
    assert(config.topic_root == "mesh-a/7F10/21A0");
    assert(config.client_id == "edge-1");
}

void check_defaults()
{
    BrokerConfig config;
    std::string error;
    assert(parse("host=h\ncafile=c\ntopic_root=t\n", config, error));
    assert(config.port == 8883);
    assert(config.client_id == "edge");
    assert(config.user.empty());
}

void check_errors()
{
    BrokerConfig config;
    std::string error;
    assert(!parse("cafile=c\ntopic_root=t\n", config, error));
    assert(error == "host is required");

    assert(!parse("host=h\ncafile=c\ntopic_root=t\nbogus=1\n", config, error));
    assert(error == "line 4: unknown key 'bogus'");

    assert(!parse("host=h\nport=70000\n", config, error));
    assert(error.find("port") != std::string::npos);

    assert(!parse("host=h\nport=12ab\n", config, error));
    assert(!parse("host=h\nport=0\n", config, error));

    assert(!parse("host=h\nnot a pair\n", config, error));
    assert(error == "line 2: expected key=value");

    assert(!load_broker_config("/nonexistent/edge.conf", config, error));
    assert(error == "cannot open /nonexistent/edge.conf");
}
} // namespace

int main()
{
    check_full_config();
    check_defaults();
    check_errors();
    return 0;
}
