#!/usr/bin/env bash
# Sourced, not executed: generation of everything a throwaway test broker and its clients need,
# from emulator/stand/stand.env. Shared by smoke.sh (broker in Docker) and ci/stand.py (broker
# started natively), so there is exactly one place that knows users, ACL and certificate layout.
#
# Needs bash, openssl and python3 on the host; no Docker and no mosquitto_passwd.
# shellcheck shell=bash

STAND_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=emulator/stand/stand.env
. "$STAND_DIR/stand.env"

# stand_certs <dir>: <dir>/certs/{ca.crt,ca.key,server.crt,server.key}. The SAN lists every name a
# client uses to reach the broker: the compose service, localhost, and 10.0.2.2, which is how a
# QEMU guest or an Android emulator reaches the host. Without it hostname verification fails for
# whichever name the cert wasn't made for. -extfile/-extensions works on real OpenSSL and on
# LibreSSL (macOS's system openssl); -copy_extensions only exists on the former. -CAserial is
# explicit because LibreSSL derives the serial file name from the CA path by cutting at the FIRST
# dot, so under a home directory like /Users/first.last/ it tries to write /Users/first.srl.
stand_certs() {
  local dir="$1" work
  work="$(mktemp -d)"
  mkdir -p "$dir/certs"
  openssl req -x509 -newkey rsa:2048 -days 1 -nodes \
    -keyout "$dir/certs/ca.key" -out "$dir/certs/ca.crt" \
    -subj "/CN=mes-stand-test-ca" >/dev/null 2>&1
  openssl req -newkey rsa:2048 -nodes \
    -keyout "$dir/certs/server.key" -out "$work/server.csr" \
    -subj "/CN=broker" >/dev/null 2>&1
  printf '[v3_req]\nsubjectAltName = DNS:broker,DNS:localhost,IP:127.0.0.1,IP:::1,IP:10.0.2.2\n' >"$work/san.cnf"
  openssl x509 -req -in "$work/server.csr" -CA "$dir/certs/ca.crt" -CAkey "$dir/certs/ca.key" \
    -CAserial "$dir/certs/ca.srl" -CAcreateserial -out "$dir/certs/server.crt" -days 1 \
    -extfile "$work/san.cnf" -extensions v3_req >/dev/null 2>&1
  rm -rf "$work"
}

# stand_passwd <dir> <user> <password>...: <dir>/passwd in mosquitto's PBKDF2-SHA512 format
# ($7$<iterations>$<salt>$<hash>, base64), written by the host user. Not mosquitto_passwd from a
# container: that wrote a root-owned file the host could not chmod on a Linux runner.
stand_passwd() {
  local dir="$1"
  shift
  python3 - "$dir/passwd" "$@" <<'PY'
import base64, hashlib, os, sys

path, pairs = sys.argv[1], sys.argv[2:]
lines = []
for user, password in zip(pairs[::2], pairs[1::2]):
    salt = os.urandom(12)
    digest = hashlib.pbkdf2_hmac("sha512", password.encode(), salt, 101)
    lines.append("%s:$7$101$%s$%s" % (user, base64.b64encode(salt).decode(), base64.b64encode(digest).decode()))
open(path, "w").write("\n".join(lines) + "\n")
PY
}

# stand_broker_conf <dir> <path>: <dir>/acl and <dir>/mosquitto.conf. <path> is where the broker
# will see <dir>: /mosquitto/generated inside the container, <dir> itself for a native broker.
# "stranger" is listed without any topic: once an acl_file is set, mosquitto denies everything not
# granted, and smoke.sh checks that this holds in both directions.
stand_broker_conf() {
  local dir="$1" path="$2"
  cat >"$dir/acl" <<EOF
user $AUTH_USER
topic readwrite $SMOKE_ROOT/#

user $STRANGER_USER

user $EDGE_USER
topic write $TOPIC_ROOT/#

user $APP_USER
topic read $TOPIC_ROOT/#
EOF
  cat >"$dir/mosquitto.conf" <<EOF
# Test-only broker: TLS + ACL, no persistence, no backend. Generated by emulator/stand/lib.sh.
listener $BROKER_PORT
cafile $path/certs/ca.crt
certfile $path/certs/server.crt
keyfile $path/certs/server.key

allow_anonymous false
password_file $path/passwd
acl_file $path/acl

persistence false
log_dest stdout
log_type error
log_type warning
log_type notice
log_type information
log_type subscribe
EOF
}

# stand_generate <dir> <path>: everything above plus the passwd file. World-readable on purpose:
# the mosquitto daemon drops to an unprivileged user while it is still parsing its config (after
# cafile/certfile/keyfile, before password_file and acl_file), so root-only files break it only
# partway through. Throwaway credentials, so nothing is lost.
stand_generate() {
  local dir="$1" path="$2"
  mkdir -p "$dir"
  stand_certs "$dir"
  stand_passwd "$dir" \
    "$AUTH_USER" "$AUTH_PASS" "$STRANGER_USER" "$STRANGER_PASS" \
    "$EDGE_USER" "$EDGE_PASS" "$APP_USER" "$APP_PASS"
  stand_broker_conf "$dir" "$path"
  chmod -R a+rX "$dir"
}

# stand_edge_conf <file> <host> <cafile>: the key=value file rpi-app/broker_config.cpp parses.
# <cafile> is where edge will find ca.crt: <dir>/certs/ca.crt on the host, /etc/edge/ca.crt in the image.
stand_edge_conf() {
  cat >"$1" <<EOF
host=$2
port=$BROKER_PORT
user=$EDGE_USER
password=$EDGE_PASS
cafile=$3
topic_root=$TOPIC_ROOT
client_id=edge
EOF
}
